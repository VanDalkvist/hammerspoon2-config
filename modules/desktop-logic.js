function remember(history,text,limit=50){if(typeof text!=="string"||!text.trim()||text.length>20000)return history;return [text,...history.filter(x=>x!==text)].slice(0,limit);}

function shouldSkip(types,bundle,secure,text){
    if(secure || /1password|bitwarden|keepass|lastpass|dashlane|passwords|keychainaccess|authy/i.test(bundle||""))return true;
    if(types.some(t=>/concealed|transient|autogenerated|password|secret/i.test(t)))return true;
    return typeof text==="string" && /-----BEGIN [^-]*PRIVATE KEY-----|\b(?:sk-(?:proj-)?[A-Za-z0-9_-]{20,}|gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|AKIA[A-Z0-9]{16}|xox[baprs]-[A-Za-z0-9-]{10,})\b|(?:password|api[_-]?key|access[_-]?token)\s*[:=]\s*\S+/i.test(text);
}

function summarizePM2(raw){
    const data=JSON.parse(raw);
    if(!Array.isArray(data))throw Error("Invalid process list");
    return data.map(p=>{
        if(!p||typeof p.name!=="string"||typeof p.pm2_env?.status!=="string")throw Error("Invalid process entry");
        const number=x=>typeof x==="number"&&Number.isFinite(x)&&x>=0?x:null;
        return {name:p.name.replace(/[\r\n\t]/g," ").slice(0,100),status:p.pm2_env.status.replace(/[^a-z_-]/gi,"").slice(0,24)||"unknown",cpu:number(p.monit?.cpu),memory:number(p.monit?.memory),restarts:number(p.pm2_env.restart_time)};
    });
}

function browserScript(id){
    const safari=["com.apple.Safari","com.apple.SafariTechnologyPreview"];
    const chromium=["com.google.Chrome","com.google.Chrome.canary","org.chromium.Chromium","com.brave.Browser","com.microsoft.edgemac","company.thebrowser.Browser","com.vivaldi.Vivaldi"];
    if(safari.includes(id))return `tell application id "${id}" to return URL of current tab of front window`;
    if(chromium.includes(id))return `tell application id "${id}" to return URL of active tab of front window`;
    return null;
}

function validURL(value){return typeof value==="string"&&/^https?:\/\/[^/\s]+[^\r\n]*$/i.test(value);}

module.exports={remember,shouldSkip,summarizePM2,browserScript,validURL};
